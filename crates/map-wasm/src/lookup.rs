#[must_use]
#[wasm_bindgen]
pub fn visit_color(count: u32) -> String {
    match count {
        50.. => "#fde724",
        25..=49 => "#6ece58",
        15..=24 => "#1f9e89",
        10..=14 => "#26828e",
        5..=9 => "#31688e",
        3..=4 => "#3e4989",
        2 => "#482878",
        1 => "#473677",
        0 => "transparent",
    }
    .to_owned()
}
