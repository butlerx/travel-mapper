#[must_use]
#[wasm_bindgen]
pub fn carrier_icon_url(carrier: &str, travel_type: &str, size: u32) -> String {
    let fallback = match travel_type {
        "air" => "/static/icons/plane.svg",
        "rail" => "/static/icons/train.svg",
        "boat" => "/static/icons/boat.svg",
        _ => "/static/icons/transport.svg",
    };

    if carrier.is_empty() {
        return format!(
            r#"<img src="{fallback}" alt="{travel_type}" width="{size}" height="{size}" style="vertical-align:middle;border-radius:50%;">"#
        );
    }

    if let Some(domain) = carrier_domain(carrier) {
        let src = format!("https://www.google.com/s2/favicons?domain={domain}&sz=64");
        let escaped = super::geo::escape_html(carrier);
        return format!(
            r#"<img src="{src}" alt="{escaped}" width="{size}" height="{size}" style="vertical-align:middle;border-radius:50%;" onerror="this.onerror=null;this.src='{fallback}';">"#
        );
    }

    format!(
        r#"<img src="{fallback}" alt="{travel_type}" width="{size}" height="{size}" style="vertical-align:middle;border-radius:50%;">"#
    )
}

